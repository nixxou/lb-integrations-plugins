# Builds src\Kronos\kronos-stv.tsv: every ST-V romset - MAME's (LaunchBox's Metadata\MAME.xml, Source sega/stv.cpp) and
# Kronos's (ctrl/src/stv.c GameList) - with whether Kronos 2.7.5 knows it, MAME's title, its parent, and for the sets Kronos
# knows the files Kronos looks for (name and CRC, as it matches them in every zip of its ROM folder: stv.c processFile).
#
#   python make-sets.py <stv.c> <MAME.xml> <kronos.exe> <out.tsv>
#
# KNOWN = in Kronos's table AND its name in kronos.exe: the binary is the authority, the source only says what the names mean
# (the source read is the fork the Windows builds come from, BenjaminSiskoo/Kronos_test - docs\kronos.md §1).
# FILES: the HEADER / BYTE / WORD blobs, each file once ("epr20825.13:94a9ad8f"); the EEPROM and RAX ones are optional to
# Kronos (stv.c updateGameList) and left out. The BIOS line, "stvbios", lists the BIOS files - any one of them will do.

import re
import sys
import xml.etree.ElementTree as ET

stv_c, mame_xml, exe, out = sys.argv[1:5]

src = open(stv_c, encoding='latin-1').read()
# As the compiler reads it: line comments out (a "// GAME_WORD_BLOB, "12", ... //NO_DUMP" is no file of the set).
src = re.sub(r'//[^\n]*', '', src)

def blobs(body):
    found = []
    for m in re.finditer(r'(HEADER_BLOB|GAME_BYTE_BLOB|GAME_WORD_BLOB|EEPROM_BLOB|RAX_BLOB|BIOS_BLOB)\s*,\s*(?:STV_\w+\s*,\s*)?"([^"]+)"\s*,\s*0x[0-9a-fA-F]+\s*,\s*0x[0-9a-fA-F]+\s*,\s*0x([0-9a-fA-F]+)', body):
        # The field is a u32: a constant of more digits ("0x0ac8deed7") is cut to 32 bits by the compiler.
        found.append((m.group(1), m.group(2), '%08x' % (int(m.group(3), 16) & 0xFFFFFFFF)))
    return found

# The BIOS.
bios_body = src[src.index('Bios BiosList'):src.index('Game GameList')]
bios_files = []
for t, f, c in blobs(bios_body):
    if (f, c) not in bios_files:
        bios_files.append((f, c))

# The games: each entry opens with { "romset", NULL|"parent", "name", and runs to its GAME_END.
games = {}
table = src[src.index('Game GameList'):]
# (a C comment may stand after the brace or a field: "{ /* ADDED: ... */")
C = r'(?:/\*.*?\*/\s*)?'
for m in re.finditer(r'\{\s*' + C + r'"([A-Za-z0-9_]+)"\s*,\s*' + C + r'(NULL|"([A-Za-z0-9_]*)")\s*,\s*' + C + r'"((?:[^"\\]|\\.)*)"\s*,', table):
    start = m.end()
    end = table.index('GAME_END', start)
    files = []
    for t, f, c in blobs(table[start:end]):
        if t in ('HEADER_BLOB', 'GAME_BYTE_BLOB', 'GAME_WORD_BLOB') and (f, c) not in files:
            files.append((f, c))
    games[m.group(1)] = {'parent': m.group(3) or '', 'name': m.group(4), 'files': files}

binary = open(exe, 'rb').read()
def in_exe(name):
    return re.search(rb'(?<![A-Za-z0-9_])' + re.escape(name.encode()) + rb'\x00', binary) is not None

# MAME's ST-V sets.
mame = {}
for el in ET.parse(mame_xml).getroot().iter('MameFile'):
    source = (el.findtext('Source') or '').strip()
    if source not in ('sega/stv.cpp', 'stv.cpp'):
        continue
    name = el.findtext('FileName').strip()
    title = (el.findtext('Name') or '').strip()
    version = (el.findtext('Version') or '').strip()
    mame[name] = {'title': title + (' ' + version if version and not version.startswith('(clone') else ''),
                  'parent': (el.findtext('CloneOf') or '').strip()}

rows = []
for name in sorted(set(mame) | set(games)):
    g, m = games.get(name), mame.get(name)
    known = g is not None and in_exe(name)
    title = m['title'] if m else g['name']
    parent = (m['parent'] if m else '') or (g['parent'] if g else '')
    files = ','.join(f + ':' + c for f, c in g['files']) if known else ''
    rows.append((name, '1' if known else '0', '1' if m else '0', title.replace('\t', ' '), parent, files))

with open(out, 'w', encoding='utf-8', newline='\r\n') as o:
    o.write('# set\tkronos\tmame\ttitle\tparent\tfiles - generated by tools/kronos-stv/make-sets.py, see there\n')
    o.write('stvbios\tbios\t1\tST-V BIOS\t\t' + ','.join(f + ':' + c for f, c in bios_files) + '\n')
    for r in rows:
        o.write('\t'.join(r) + '\n')

kronos_only = [n for n in games if n not in mame]
not_in_exe = [n for n in games if not in_exe(n)]
print('MAME ST-V sets:', len(mame), '- Kronos table:', len(games), '- known (table + exe):', sum(1 for r in rows if r[1] == '1'))
print('in Kronos, not in MAME.xml:', ', '.join(kronos_only) or '-')
print('in the source, not in kronos.exe:', ', '.join(not_in_exe) or '-')
print('BIOS files:', len(bios_files))
