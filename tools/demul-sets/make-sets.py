# Builds src/Demul/demul-sets.tsv: every MAME romset of the boards Demul emulates, the board it belongs
# to, whether demul.exe knows it by name, and MAME's title for it.
#
#   python tools/demul-sets/make-sets.py <mame -listxml output> <demul.exe> > src/Demul/demul-sets.tsv
#
# THE BOARD of a set is the BIOS reached by following romof from it (MAME -listxml): naomi, naomigd and
# the game BIOSes on Naomi (hod2bios, f355bios, f355dlx, airlbios) are Naomi; naomi2 is Naomi 2; awbios
# is Atomiswave - in sega/dc_atomiswave.cpp, not naomi.cpp, since MAME split it out; segasp, hikaru are
# themselves; cv1k.cpp and atvtrack.cpp (Gaelco's PowerVR board) have no BIOS and go by driver.
#
# "KNOWN TO DEMUL" is the set's name among the strings of demul.exe - ASCII or UTF-16 - which is how its
# game table is stored. It says Demul has the set, not that it plays it.
#
# Generated 2026-10-06 from MAME 0.288 and demul.exe of demul_251220.7z.

import re, sys, xml.etree.ElementTree as ET

DRIVERS = {'sega/naomi.cpp', 'sega/dc_atomiswave.cpp', 'sega/segasp.cpp', 'sega/hikaru.cpp', 'cave/cv1k.cpp', 'gaelco/atvtrack.cpp'}
BOARD_OF_BIOS = {'naomi': 'Naomi', 'naomigd': 'Naomi', 'hod2bios': 'Naomi', 'f355bios': 'Naomi', 'f355dlx': 'Naomi',
                 'airlbios': 'Naomi', 'naomi2': 'Naomi 2', 'awbios': 'Atomiswave', 'segasp': 'System SP', 'hikaru': 'Hikaru'}
BOARD_OF_DRIVER = {'cave/cv1k.cpp': 'CV1000', 'gaelco/atvtrack.cpp': 'Gaelco'}

machines = {}
for _, el in ET.iterparse(sys.argv[1], events=('end',)):
    if el.tag != 'machine':
        continue
    if el.get('sourcefile') in DRIVERS:
        machines[el.get('name')] = (el.get('sourcefile'), el.get('romof'), el.get('isbios') == 'yes', el.findtext('description') or '')
    el.clear()

exe = open(sys.argv[2], 'rb').read()
known = {m.decode() for m in re.findall(rb'[\x20-\x7e]{3,}', exe)} | {m.decode('utf-16le') for m in re.findall(rb'(?:[\x20-\x7e]\x00){3,}', exe)}

def board(name):
    src, romof, isbios, _ = machines[name]
    if src in BOARD_OF_DRIVER:
        return BOARD_OF_DRIVER[src]
    seen = set()
    while name in machines and name not in seen:
        seen.add(name)
        if machines[name][2]:
            return BOARD_OF_BIOS.get(name)
        name = machines[name][1]
    return BOARD_OF_BIOS.get(name)

out = sys.stdout
out.write('# set\tboard\tdemul\ttitle - generated by tools/demul-sets/make-sets.py, see there\n')
for name in sorted(machines):
    b = board(name)
    if b is None:
        continue
    kind = 'BIOS' if machines[name][2] else b
    out.write('%s\t%s\t%d\t%s\n' % (name, kind if kind == 'BIOS' else b, 1 if name in known else 0, machines[name][3].replace('\t', ' ')))
