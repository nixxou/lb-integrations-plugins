# The table of ZiNc 1.1's games the ZincEx plugin carries (src\ZincEx\zinc-games.tsv), from ZiNc's own listings.
#
#   ZiNc.exe --list-games > list-games.txt     "  12 Street Fighter EX 2 PLUS (ASIA 990611) [sfex2pa, parent sfex2p, BIOS cpzn2]"
#   ZiNc.exe --list-sets  > list-sets.txt      the same title line, then one "<file>  <crc32>" line per ROM, a blank line
#
# Both were taken on 15/10 from the ZiNc.exe of the ZiNc-EX v1.0.0 release (ZiNc 1.1, 2005-01-25: it will not change),
# and are kept here beside this script. Run from the repository root:
#
#   python -I tools\zinc-games\make-table.py
#
# One line per game, tab-separated: id, set, parent, BIOS set, title, then every ROM as <file>:<crc32> separated by spaces.
# The id is the number ZiNc starts a game by; the set is the name ZiNc EX takes on its --game.

import os
import re

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(os.path.dirname(here))

title_re = re.compile(r'^\s*(\d+)\s+(.*?)\s*\[([^\]]+)\]\s*$')
games = []
for line in open(os.path.join(here, 'list-games.txt'), encoding='latin-1'):
    m = title_re.match(line.rstrip('\r\n'))
    if not m:
        continue
    parts = [p.strip() for p in m.group(3).split(',')]
    g = {'id': int(m.group(1)), 'title': m.group(2), 'set': parts[0], 'parent': '', 'bios': '', 'roms': []}
    for p in parts[1:]:
        if p.startswith('parent '):
            g['parent'] = p[7:].strip()
        elif p.startswith('BIOS '):
            g['bios'] = p[5:].strip()
    games.append(g)

by_set = {g['set']: g for g in games}
current = None
for line in open(os.path.join(here, 'list-sets.txt'), encoding='latin-1'):
    line = line.rstrip('\r\n')
    rom = re.match(r'^(\S+)\s+([0-9a-f]{8})$', line)
    if rom and current is not None:
        current['roms'].append(rom.group(1) + ':' + rom.group(2))
        continue
    head = re.match(r'^.*\[([^\],]+)[^\]]*\]\s*$', line)
    current = by_set.get(head.group(1).strip()) if head else None

missing = [g['set'] for g in games if not g['roms']]
if missing:
    raise SystemExit('no ROM list for: ' + ', '.join(missing))

out = os.path.join(root, 'src', 'ZincEx', 'zinc-games.tsv')
with open(out, 'w', encoding='utf-8', newline='\r\n') as f:
    f.write('# id\tset\tparent\tbios\ttitle\troms (file:crc32) - generated by tools\\zinc-games\\make-table.py from ZiNc 1.1\'s own listings\n')
    for g in sorted(games, key=lambda g: g['id']):
        f.write('\t'.join([str(g['id']), g['set'], g['parent'], g['bios'], g['title'], ' '.join(g['roms'])]) + '\n')
print(str(len(games)) + ' games -> ' + out)
